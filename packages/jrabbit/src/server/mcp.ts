type Content =
  | { type: "text"; text: string }
  | { type: "image"; data: string; mimeType: string };

/** Screenshots per response. More would cost the agent a lot of context for little gain. */
const MAX_IMAGES = 8;

/** Most MCP clients cut tool calls at 60 s (Codex by default), so a wait must end before that. */
const MAX_WAIT_SECONDS = 55;
const DEFAULT_WAIT_SECONDS = 50;
/** open_review also starts the dev server probe and the proxy, so it waits a bit less. */
const OPEN_WAIT_SECONDS = 45;
/**
 * resolve_feedback waits at most this long for after screenshots, however many pins it got,
 * so a batch ends well before the client's 60 s limit even when the browser is elsewhere.
 */
const AFTER_SHOT_BUDGET_MS = 45_000;

/**
 * How long to wait for the after shot of the i-th pin in a batch. The overlay captures one
 * after another, so later pins get more time, but never more than the batch budget.
 */
export function afterShotTimeout(i: number, budgetMs = AFTER_SHOT_BUDGET_MS): number {
  return Math.min(15_000 + i * 4_000, budgetMs);
}

const INSTRUCTIONS = `jrabbit lets a human point at UI in their browser and leave feedback pins for you.

Stay in the loop. You only receive pins while you are inside wait_for_feedback, and jrabbit cannot wake you once your turn ends. So after open_review, do not end your turn: keep calling wait_for_feedback until the human says they are done. A sent pin is the request itself: change the code without asking the human to confirm.

Loop:
1. Tell the human in one line to point (P), comment and press Send. Then open_review(url) with the app's dev server URL: it opens the browser and already waits for the first pins.
2. wait_for_feedback(). If it times out, call it again right away: the human may still be pinning.
3. For each pin, edit the code. pin.source is where the pointed element is written; sourceChain lists the owner components. pin.element.styles has the element's current computed styles. When pin.source is null, search the code with pin.find.
4. resolve_feedback for each pin, or for several at once with pins: [{id, summary}]. It captures an after screenshot: look at it and fix again if it is not right.
5. Go back to wait_for_feedback() for the next batch or for pins the human reopened.

Rules: call list_rules() before editing and follow every approved rule. When the human repeats the same correction, propose_rule() so it becomes a draft rule they can approve. update_rule() rewords a rule (it goes back to draft); delete_rule() removes a draft.

If the human says they sent feedback, or asks you to check jrabbit, call wait_for_feedback (not list_feedback): it hands you the pins to work on.

When the human is done with approved pins, archive_feedback() moves them out of the way.
Never claim a human approved anything. Approving is done by the human in the browser.`;

// Class names generated by CSS-in-JS or CSS modules (e.g. "css-1a2b3c", "Header_nav__x9Yz2") never appear in the source.
const HASHED = /(^|[_-])(?=[a-z0-9]*\d)(?=[a-z0-9]*[a-z])[a-z0-9]{5,}$/i;

/** Strings the agent can search for when the source location is unknown. */
export function searchHints(el: PinElement): string[] {
  const hints: string[] = [];
  const attrs = el.attrs ?? {};
  for (const key of ["data-testid", "id", "aria-label", "alt", "placeholder", "title"]) {
    if (attrs[key]) hints.push(`${key}="${attrs[key]}"`);
  }
  if (el.text) hints.push(`text "${el.text.slice(0, 60)}"`);
  const classes = (el.classes ?? []).filter((c) => !HASHED.test(c)).slice(0, 6);
  if (classes.length) hints.push(`class ${classes.join(" ")}`);
  if (el.component) hints.push(`component ${el.component}`);
  return hints;
}

export function formatPin(p: Pin) {
  const loc = (l: { file: string; line: number; column?: number; component?: string }) =>
    `${l.file}:${l.line}${l.column ? `:${l.column}` : ""}${l.component ? ` (${l.component})` : ""}`;
  const { rect: _rect, ...element } = p.element;
  return {
    id: p.id,
    n: p.n,
    status: p.status,
    comment: p.comment,
    notes: p.history.filter((h) => h.note).map((h) => `${h.by}: ${h.note}`),
    page: p.page.path,
    viewport: `${p.viewport.width}x${p.viewport.height}@${p.viewport.dpr}x`,
    element: { ...element, size: `${p.element.rect.width}x${p.element.rect.height}` },
    source: p.source ? loc(p.source) : null,
    sourceChain: p.sourceChain.map(loc),
    ...(p.source ? {} : { find: searchHints(p.element) }),
    shots: p.shots,
    ...(p.resolution ? { resolution: p.resolution.summary } : {}),
  };
}

export function formatRule(r: Rule) {
  return { slug: r.slug, title: r.title, status: r.status, rule: r.body, source: r.source, path: r.path };
}

async function pinContent(store: Store, pins: Pin[], kinds: Array<"before" | "after">): Promise<Content[]> {
  const out: Content[] = [];
  const omitted: number[] = [];
  let images = 0;
  for (const p of pins) {
    for (const kind of kinds) {
      if (!p.shots[kind]) continue;
      if (images >= MAX_IMAGES) {
        if (!omitted.includes(p.n)) omitted.push(p.n);
        continue;
      }
      const data = await store.readShotBase64(p.shots[kind]);
      if (!data) continue;
      out.push({ type: "text", text: `#${p.n} ${kind}:` });
      out.push({ type: "image", data, mimeType: "image/png" });
      images++;
    }
  }
  if (omitted.length) {
    const list = omitted.map((n) => `#${n}`).join(", ");
    out.push({ type: "text", text: `Screenshots for ${list} were left out to keep this response small. Call get_feedback for each one.` });
  }
  return out;
}

const text = (value: unknown): Content => ({
  type: "text",
  text: typeof value === "string" ? value : JSON.stringify(value, null, 2),
});

const fail = (message: string) => ({ content: [text(message)], isError: true });

/** The first local folder the client calls its workspace, if any. */
export function clientRoot(uris: string[]): string | null {
  for (const uri of uris) {
    if (!uri.startsWith("file://")) continue;
    try {
      const path = fileURLToPath(uri);
      if (statSync(path).isDirectory()) return path;
    } catch {
      /* not a usable folder */
    }
  }
  return null;
}

const READ_ONLY = { readOnlyHint: true, openWorldHint: false } as const;
const LOCAL_WRITE = { readOnlyHint: false, destructiveHint: false, openWorldHint: false } as const;

export interface McpOptions {
  /**
   * Use the client's workspace folder (MCP roots) as the project root when it offers one.
   * Off when the root was set explicitly (JRABBIT_ROOT).
   */
  clientRoots?: boolean;
  /** Overall wait for after screenshots in one resolve_feedback call. Tests shorten it. */
  afterShotBudgetMs?: number;
}

export function createMcpServer(store: Store, review: ReviewServer, version: string, options: McpOptions = {}): McpServer {
  const server = new McpServer({ name: "jrabbit", version }, { instructions: INSTRUCTIONS });
  let rootReady: () => void = () => undefined;
  const rootSettled = new Promise<void>((r) => (rootReady = r));
  /** Every tool waits for this, so nothing touches the store before its root is known. */
  const ready = () => rootSettled;
  if (!options.clientRoots) rootReady();

  server.server.oninitialized = () => {
    if (review.agent === "none") review.setAgent("connected");
    const useRoots = options.clientRoots && server.server.getClientCapabilities()?.roots;
    if (!useRoots) return rootReady();
    server.server
      .listRoots(undefined, { timeout: 3000 })
      .then(({ roots }) => {
        const root = clientRoot(roots.map((r) => r.uri));
        if (root && root !== store.root) {
          store.useRoot(root);
          log(`project root from client: ${root}`);
        }
      })
      .catch((err) => log("roots unavailable, using the current directory", err))
      .finally(rootReady);
  };
  let waiting = 0;
  /** open_review ran and no browser has connected since: do not reopen the browser in a loop. */
  let reopenedForNobody = false;
  type Extra = RequestHandlerExtra<ServerRequest, ServerNotification>;

  /** Wait for sent pins: in this process, through store changes from other processes, or polling every 2 s. */
  const waitForPins = async (seconds: number, extra: Extra) => {
    const deadline = Date.now() + seconds * 1000;
    const progressToken = extra._meta?.progressToken;
    waiting++;
    review.setAgent("listening");
    try {
      let claim = await store.claimUndelivered(process.pid);
      while (!claim.pins.length && Date.now() < deadline && !extra.signal.aborted) {
        await store.beat("agent");
        await new Promise<void>((resolve) => {
          const done = () => {
            clearTimeout(timer);
            review.off("sent", done);
            review.off("changed", done);
            extra.signal.removeEventListener("abort", done);
            resolve();
          };
          const timer = setTimeout(done, Math.min(2000, Math.max(0, deadline - Date.now())));
          review.on("sent", done);
          review.on("changed", done);
          extra.signal.addEventListener("abort", done);
        });
        claim = await store.claimUndelivered(process.pid);
        if (!claim.pins.length && progressToken !== undefined) {
          const elapsed = seconds - Math.max(0, Math.round((deadline - Date.now()) / 1000));
          await extra
            .sendNotification({
              method: "notifications/progress",
              params: { progressToken, progress: elapsed, total: seconds, message: "Waiting for the human to press Send" },
            })
            .catch(() => undefined);
        }
      }
      return claim;
    } finally {
      waiting--;
      if (!waiting) review.setAgent("connected");
    }
  };

  /** The result of a wait: the pins to work on, or what to do next. Shared by open_review and wait_for_feedback. */
  const feedbackContent = async ({ pins, redelivered }: { pins: Pin[]; redelivered: Pin[] }): Promise<Content[]> => {
    if (!pins.length) {
      const drafts = (await store.listPins()).filter((p) => p.status === "draft").length;
      const connected = await review.overlayConnected();
      const gone = !connected && reopenedForNobody;
      if (connected) reopenedForNobody = false;
      return [
        text({
          status: "timeout",
          drafts,
          overlayConnected: connected,
          next: gone
            ? `Nobody has the review open: the human closed it or stepped away. Stop waiting and tell them in one line: open ${review.origin ?? "the review URL"} again, send pins, and say "check jrabbit".`
            : connected
              ? `Nothing sent yet${drafts ? ` (${drafts} draft${drafts === 1 ? "" : "s"} not sent)` : ""}. Call wait_for_feedback again now. Do not end your turn until the human says they are done.`
              : "No browser is connected to the review. Call open_review again: it reopens the browser. Then keep waiting.",
        }),
      ];
    }
    const rules = (await store.listRules()).filter((r) => r.status === "approved");
    return [
      text({
        status: "feedback",
        pins: pins.map(formatPin),
        ...(redelivered.length && {
          redelivered: redelivered.map((p) => p.n),
          redeliveredNote:
            "These pins went to an earlier session that did not resolve them. Check whether the change is already in the code before editing again.",
        }),
        approvedRules: rules.map(formatRule),
        next: "Edit the code for each pin now, without asking the human to confirm: sending the pin is the request. Then call resolve_feedback(id, summary) for each one, and wait_for_feedback again.",
      }),
      ...(await pinContent(store, pins, ["before"])),
    ];
  };

  server.registerTool(
    "open_review",
    {
      title: "Open review",
      description: `Open the app in the browser with the jrabbit overlay so the human can point at elements and comment, then wait for their first pins (like wait_for_feedback, up to ${OPEN_WAIT_SECONDS} s). Before calling it, tell the human in one line: press P to point at an element, comment, and press Send. Proxies the dev server; the project's code is not modified. Fails with a clear reason if nothing is running at the URL.`,
      inputSchema: {
        url: z.string().describe("Dev server URL, e.g. http://localhost:3000 or http://localhost:3000/pricing"),
        open: z.boolean().optional().describe("Open the browser (default true)"),
        wait_seconds: z
          .number()
          .int()
          .min(0)
          .max(OPEN_WAIT_SECONDS)
          .optional()
          .describe(`How long to wait for the first pins. Default ${OPEN_WAIT_SECONDS}; 0 returns right away`),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: true },
    },
    async ({ url, open, wait_seconds }, extra) => {
      await ready();
      let reviewUrl: string;
      try {
        reviewUrl = await review.start(url);
      } catch (err) {
        return fail(`Could not open review: ${(err as Error).message}`);
      }
      if (open !== false) openBrowser(reviewUrl);
      reopenedForNobody = !(await review.overlayConnected());
      const info = {
        reviewUrl,
        target: url,
        ...(open === false && { tell: "Give the human the review URL to open." }),
        ...(new URL(reviewUrl).hostname === review.target?.hostname && {
          login:
            "The review shares cookies with the dev server (same host name). If signing in lands the human on the dev server URL (OAuth callbacks), they open the review URL again and stay signed in.",
        }),
      };
      const seconds = wait_seconds ?? OPEN_WAIT_SECONDS;
      if (!seconds) {
        return {
          content: [
            text({
              ...info,
              next: "Call wait_for_feedback now, in this same turn. Do not end your turn while the review is open: jrabbit cannot wake you.",
            }),
          ],
        };
      }
      return { content: [text(info), ...(await feedbackContent(await waitForPins(seconds, extra)))] };
    },
  );

  server.registerTool(
    "wait_for_feedback",
    {
      title: "Wait for feedback",
      description: `Block until the human presses Send (or reopens a pin), then return the new pins with screenshots and source locations. Returns immediately if there are pins you have not received yet. Waits at most ${MAX_WAIT_SECONDS} s; on timeout, call it again. Keep calling it until the human says they are done.`,
      inputSchema: {
        timeout_seconds: z
          .number()
          .int()
          .min(1)
          .max(MAX_WAIT_SECONDS)
          .optional()
          .describe(`Default ${DEFAULT_WAIT_SECONDS}`),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: false },
    },
    async ({ timeout_seconds }, extra) => {
      await ready();
      return { content: await feedbackContent(await waitForPins(timeout_seconds ?? DEFAULT_WAIT_SECONDS, extra)) };
    },
  );

  server.registerTool(
    "list_feedback",
    {
      title: "List feedback",
      description: "List pins, optionally filtered by status. No images; use get_feedback for one pin with screenshots.",
      inputSchema: {
        status: z.enum(["draft", "open", "resolved", "approved"]).optional(),
        page: z.string().optional().describe("Only pins on this path, e.g. /pricing"),
      },
      annotations: READ_ONLY,
    },
    async ({ status, page }) => {
      await ready();
      const pins = (await store.listPins()).filter(
        (p) => (!status || p.status === (status as PinStatus)) && (!page || p.page.path === page),
      );
      const waiting = pins.filter((p) => p.status === "open" && !p.deliveredAt).length;
      return {
        content: [
          text({
            count: pins.length,
            pins: pins.map(formatPin),
            ...(waiting && {
              next: `${waiting} sent pin${waiting === 1 ? " is" : "s are"} waiting for you. Call wait_for_feedback to receive them with screenshots, change the code for each one without asking first, and resolve_feedback.`,
            }),
          }),
        ],
      };
    },
  );

  server.registerTool(
    "get_feedback",
    {
      title: "Get feedback",
      description: "Get one pin by id or number, with its before/after screenshots.",
      inputSchema: { id: z.string().describe("Pin id (pin_…) or number (3 or #3)") },
      annotations: READ_ONLY,
    },
    async ({ id }) => {
      await ready();
      const pin = await store.getPin(id);
      if (!pin) return fail(`No pin ${id}`);
      return { content: [text(formatPin(pin)), ...(await pinContent(store, [pin], ["before", "after"]))] };
    },
  );

  server.registerTool(
    "resolve_feedback",
    {
      title: "Resolve feedback",
      description:
        `Mark pins as resolved after you changed the code: one with id + summary, or several with pins: [{id, summary}]. Captures after screenshots in the human's browser (several at once when batched, ${AFTER_SHOT_BUDGET_MS / 1000} s at most) and returns before/after so you can verify. Idempotent. This does not approve: only the human approves.`,
      inputSchema: {
        id: z.string().optional().describe("Pin id (pin_…) or number, to resolve one pin"),
        summary: z.string().optional().describe("What you changed, in one or two sentences, for the human"),
        pins: z
          .array(z.object({ id: z.string(), summary: z.string().min(1) }))
          .min(1)
          .max(20)
          .optional()
          .describe("Resolve several pins in one call"),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: true },
    },
    async ({ id, summary, pins: batch }) => {
      await ready();
      const items = batch ?? (id && summary?.trim() ? [{ id, summary: summary.trim() }] : []);
      if (!items.length) return fail("Pass id and summary, or pins: [{id, summary}].");

      const errors: string[] = [];
      const resolved: Pin[] = [];
      for (const item of items) {
        const found = await store.getPin(item.id);
        if (!found) {
          errors.push(`No pin ${item.id}`);
          continue;
        }
        if (found.status === "draft") {
          errors.push(`Pin #${found.n} is a draft: the human has not sent it yet.`);
          continue;
        }
        const pin = await store.updatePin(found.id, (p) => {
          if (p.status !== "resolved" || p.resolution?.summary !== item.summary) {
            if (p.status !== "approved") store.setStatus(p, "resolved", "agent", item.summary);
            p.resolution = { summary: item.summary, at: new Date().toISOString() };
          }
        });
        resolved.push(pin ?? found);
      }
      if (!resolved.length) return fail(errors.join("\n"));
      review.broadcastState();

      const budget = options.afterShotBudgetMs ?? AFTER_SHOT_BUDGET_MS;
      const after = await Promise.all(resolved.map((p, i) => review.requestAfterShot(p, afterShotTimeout(i, budget))));
      const pins = resolved.map((p, i) => after[i] ?? p);
      review.toast(`${pins.map((p) => `#${p.n}`).join(" ")} resolved`);

      const captured = (p: Pin) => Boolean(p.shots.after && after[pins.indexOf(p)]);
      const afterShot = (p: Pin) =>
        captured(p) ? "captured" : review.connectedClients ? "not captured" : "not captured (no browser connected)";
      const missed = review.connectedClients ? pins.filter((p) => !captured(p)) : [];
      const paths = [...new Set(missed.map((p) => p.page.path))];
      const notice = missed.length
        ? `The browser did not capture ${missed.map((p) => `#${p.n}`).join(" ")} in time. The human is probably on another page than ${paths.join(", ")}, or the element is gone. Ask them to open ${paths.length === 1 ? "that page" : "those pages"}, then resolve ${missed.length === 1 ? "that pin" : "those pins"} again to capture the after shot.`
        : undefined;
      const next = "Compare before/after. If it is not right, fix it and resolve again. Then call wait_for_feedback: the human approves, reopens or sends more pins in the browser.";
      const summaryText =
        pins.length === 1 && !batch
          ? { pin: formatPin(pins[0]!), afterShot: afterShot(pins[0]!), ...(notice ? { notice } : {}), next }
          : { resolved: pins.map((p) => ({ pin: formatPin(p), afterShot: afterShot(p) })), ...(errors.length ? { errors } : {}), ...(notice ? { notice } : {}), next };
      return { content: [text(summaryText), ...(await pinContent(store, pins, ["before", "after"]))] };
    },
  );

  server.registerTool(
    "reopen_feedback",
    {
      title: "Reopen feedback",
      description: "Reopen a resolved pin, e.g. when the after screenshot shows the change did not work.",
      inputSchema: { id: z.string(), reason: z.string().optional() },
      annotations: { ...LOCAL_WRITE, idempotentHint: true },
    },
    async ({ id, reason }) => {
      await ready();
      const found = await store.getPin(id);
      if (!found) return fail(`No pin ${id}`);
      const pin = await store.updatePin(found.id, (p) => {
        if (p.status !== "draft") store.setStatus(p, "open", "agent", reason);
      });
      review.broadcastState();
      return { content: [text(formatPin(pin!))] };
    },
  );

  server.registerTool(
    "propose_rule",
    {
      title: "Propose rule",
      description:
        "Save a repeated correction as a draft rule in .jrabbit/rules/ (versioned with the repo). Drafts do not apply until the human approves them in the browser.",
      inputSchema: {
        title: z.string().min(3).describe("Short imperative title, e.g. 'No neutral grays'"),
        rule: z.string().min(3).describe("The rule, specific and checkable"),
        pins: z.array(z.string()).optional().describe("Pin ids or numbers this rule comes from"),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: false },
    },
    async ({ title, rule, pins }) => {
      await ready();
      const ids: string[] = [];
      for (const ref of pins ?? []) {
        const p = await store.getPin(ref);
        if (p) ids.push(p.id);
      }
      const created = await store.writeRule({ title, body: rule, source: ids });
      review.broadcastState();
      return {
        content: [text({ rule: formatRule(created), next: "Tell the human a draft rule is waiting for approval in the overlay." })],
      };
    },
  );

  server.registerTool(
    "list_rules",
    {
      title: "List rules",
      description: "List taste rules. Follow every approved rule when editing UI.",
      inputSchema: { status: z.enum(["draft", "approved"]).optional() },
      annotations: READ_ONLY,
    },
    async ({ status }) => {
      await ready();
      const rules = (await store.listRules()).filter((r) => !status || r.status === status);
      return { content: [text({ count: rules.length, rules: rules.map(formatRule) })] };
    },
  );

  server.registerTool(
    "update_rule",
    {
      title: "Update rule",
      description:
        "Reword a rule's title or text. The rule goes back to draft, even if it was approved: the human approves the new wording before it applies.",
      inputSchema: {
        slug: z.string().describe("Rule slug, from list_rules"),
        title: z.string().min(3).optional(),
        rule: z.string().min(3).optional().describe("The new rule text"),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: true },
    },
    async ({ slug, title, rule }) => {
      await ready();
      if (!title && !rule) return fail("Pass a new title, rule text, or both.");
      const updated = await store.updateRule(slug, { title, body: rule });
      if (!updated) return fail(`No rule ${slug}`);
      review.broadcastState();
      return { content: [text({ rule: formatRule(updated), next: "Tell the human the rule is back in draft, waiting for approval." })] };
    },
  );

  server.registerTool(
    "delete_rule",
    {
      title: "Delete rule",
      description: "Delete a draft rule you proposed. Approved rules belong to the human: they remove them in the browser.",
      inputSchema: { slug: z.string().describe("Rule slug, from list_rules") },
      annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: true, openWorldHint: false },
    },
    async ({ slug }) => {
      await ready();
      const rule = await store.readRule(slug);
      if (!rule) return fail(`No rule ${slug}`);
      if (rule.status === "approved") {
        return fail(`"${rule.title}" is approved. Ask the human to remove it in the overlay (Rules tab), or to delete ${rule.path}.`);
      }
      await store.deleteRule(slug);
      review.broadcastState();
      return { content: [text({ deleted: slug })] };
    },
  );

  server.registerTool(
    "archive_feedback",
    {
      title: "Archive feedback",
      description:
        "Move approved pins and their screenshots to .jrabbit/archive/ so lists stay short. Only approved pins move; pin numbers are never reused.",
      inputSchema: {
        pins: z.array(z.string()).optional().describe("Pin ids or numbers. Default: every approved pin"),
      },
      annotations: { ...LOCAL_WRITE, idempotentHint: true },
    },
    async ({ pins }) => {
      await ready();
      const archived = await store.archivePins(pins);
      review.broadcastState();
      return {
        content: [text({ archived: archived.map((p) => `#${p.n}`), folder: `${store.dir}/archive` })],
      };
    },
  );

  server.registerTool(
    "status",
    {
      title: "Status",
      description: "Review state: URL, connected browsers, pin counts by status, rules, and where the store lives.",
      inputSchema: {},
      annotations: READ_ONLY,
    },
    async () => {
      await ready();
      const pins = await store.listPins();
      const rules = await store.listRules();
      const count = (s: PinStatus) => pins.filter((p) => p.status === s).length;
      return {
        content: [
          text({
            review: review.origin ? { url: review.origin, target: review.target?.origin } : null,
            browsersConnected: review.connectedClients,
            overlayConnected: await review.overlayConnected(),
            agentWaiting: review.agentState === "listening",
            pins: { draft: count("draft"), open: count("open"), resolved: count("resolved"), approved: count("approved") },
            undelivered: pins.filter((p) => p.status === "open" && !p.deliveredAt).length,
            rules: { draft: rules.filter((r) => r.status === "draft").length, approved: rules.filter((r) => r.status === "approved").length },
            store: store.dir,
          }),
        ],
      };
    },
  );

  // Shows up as a slash command in clients that support MCP prompts (e.g. /mcp__jrabbit__review in Claude Code).
  server.registerPrompt(
    "review",
    {
      title: "Review the UI with jrabbit",
      description: "Open a jrabbit review of the dev server and work through the human's pins.",
      argsSchema: { url: z.string().optional().describe("Dev server URL. Leave empty to find the running one.") },
    },
    ({ url }) => ({
      messages: [
        {
          role: "user",
          content: {
            type: "text",
            text: [
              url
                ? `Open a jrabbit review of ${url}.`
                : "Find this project's running local dev server (check the dev script and which localhost ports are listening) and open a jrabbit review of it. If none is running, ask me to start it.",
              "Then follow the jrabbit loop: wait_for_feedback, change the code for each pin, resolve_feedback with a short summary, check the after screenshot, and wait again until I say we are done.",
            ].join(" "),
          },
        },
      ],
    }),
  );

  return server;
}

export async function runMcp(store: Store, review: ReviewServer, version: string, options: McpOptions = {}): Promise<void> {
  const server = createMcpServer(store, review, version, options);
  await server.connect(new StdioServerTransport());
  const shutdown = async () => {
    await review.stop();
    process.exit(0);
  };
  process.stdin.on("close", shutdown);
  process.on("SIGTERM", shutdown);
  process.on("SIGINT", shutdown);
}
